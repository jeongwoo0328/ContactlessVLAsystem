# =========================================================

import math

class GraspSkill:
    def __init__(self, robot):
        self.robot = robot

    def execute(self, intent, scene_data):
        """
        물체 탐지 데이터를 우회하여 항상 정해진 물리 관절 각도로 동작하는 고정 자동화 시퀀스입니다.
        
        [하드웨어 목표 각도 반영 계산 수치 (라디안 역산값)]
        1. 11번 핀 (그리퍼 / joint_3):
           - 열림 (0도)  -> -1.571 rad  (공식: degrees + 90)
           - 닫힘 (90도) ->  0.000 rad  (공식: degrees + 90)
        2. 7번 핀 (어깨 피치 / joint_1):
           - 목표 (140도) -> -0.524 rad  (공식: 90 - degrees + 20)
        3. 9번 핀 (팔꿈치 피치 / joint_2):
           - 목표 (150도) ->  1.047 rad  (공식: degrees + 90)
        """

        # 정밀 역산된 라디안 상수 정의
        PIN_11_OPEN = -1.571    # 아두이노 11번 핀 -> 0도 (완전 열림)
        PIN_11_CLOSE = 0.000    # 아두이노 11번 핀 -> 90도 (완전 닫힘)
        PIN_7_TARGET = -0.524   # 아두이노 7번 핀  -> 140도
        PIN_9_TARGET = 1.047    # 아두이노 9번 핀  -> 150도

        print("[고정 집기 스킬] 계산된 정밀 하드웨어 각도로 하강 및 집기 시퀀스를 실행합니다.")
        print(f"-> 목표 하드웨어 각도: 7번 핀(joint_1)={140}도, 9번 핀(joint_2)={150}도")
        print(f"-> 그리퍼(11번 핀): 열림 {0}도 -> 닫힘 {90}도")

        actions = []

        # -------------------------------------------------
        # 단계 1: 공중 대기 및 그리퍼 완전 개방 (11번 핀 -> 0도)
        # -------------------------------------------------
        actions.append({
            "joint_0": getattr(self.robot, "current_joint_0", 0.0),
            "joint_1": -0.20,            # 진입 전 안전한 전천후 중간 높이
            "joint_2": 0.50,
            "joint_3": PIN_11_OPEN,      # 그리퍼 완전 열림 (0도 전송용)
            "joint_4": 0.0,
            "steps": 100
        })

        # -------------------------------------------------
        # 단계 2: 목표 위치 도달 (7번 핀 -> 140도, 9번 핀 -> 150도 유지하며 하강)
        # -------------------------------------------------
        actions.append({
            "joint_0": getattr(self.robot, "current_joint_0", 0.0),
            "joint_1": PIN_7_TARGET,     # 어깨 각도 140도 위치로 이동
            "joint_2": PIN_9_TARGET,     # 팔꿈치 각도 150도 위치로 이동
            "joint_3": PIN_11_OPEN,      # 그리퍼 열림 유지 (0도)
            "joint_4": 0.0,
            "steps": 120
        })

        # -------------------------------------------------
        # 단계 3: 대상 고정 위치에서 쥐기 실행 (11번 핀 -> 90도 닫힘)
        # -------------------------------------------------
        actions.append({
            "joint_0": getattr(self.robot, "current_joint_0", 0.0),
            "joint_1": PIN_7_TARGET,     # 하강 상태 홀딩
            "joint_2": PIN_9_TARGET,     # 하강 상태 홀딩
            "joint_3": PIN_11_CLOSE,     # 그리퍼 단단히 닫기 (90도)
            "joint_4": 0.0,
            "steps": 100
        })

        # -------------------------------------------------
        # 단계 4: 물체를 쥔 상태로 안전하게 들어올리기
        # -------------------------------------------------
        actions.append({
            "joint_0": getattr(self.robot, "current_joint_0", 0.0),
            "joint_1": PIN_7_TARGET - 0.3, # 안전 고도로 들어 올리기 위해 관절 상향 조정 (-0.3)
            "joint_2": PIN_9_TARGET - 0.2, # 관절 상향 조정 (-0.2)
            "joint_3": PIN_11_CLOSE,       # 집게가 풀리지 않도록 다물기 상태 유지 (90도)
            "joint_4": 0.0,
            "steps": 120
        })

        return {
            "type": "sequence",
            "actions": actions
        }